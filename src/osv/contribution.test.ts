import { describe, expect, test } from "vitest";

import { isEmptyLockfile } from "./contribution.js";

// M6 final cleanup: a lockfile that lists no dependency is a real fix, not an unreadable lockfile.
describe("isEmptyLockfile", () => {
  test.each<[string, string, boolean]>([
    ["package-lock.json", JSON.stringify({ name: "x", lockfileVersion: 3, requires: true, packages: { "": { name: "x" } } }), true],
    ["npm-shrinkwrap.json", JSON.stringify({ name: "x", lockfileVersion: 1, dependencies: {} }), true],
    ["package-lock.json", JSON.stringify({ name: "x", lockfileVersion: 3, packages: { "": {}, "node_modules/lodash": { version: "4.17.4" } } }), false],
    ["package-lock.json", JSON.stringify({ name: "x", lockfileVersion: 2, packages: { "": {} }, dependencies: { lodash: { version: "4.17.4" } } }), false],
    ["package-lock.json", "{}", false],
    ["package-lock.json", "{ not json", false],
    ["composer.lock", JSON.stringify({ packages: [], "packages-dev": [] }), true],
    ["composer.lock", JSON.stringify({ packages: [], "packages-dev": null }), true],
    ["composer.lock", JSON.stringify({ packages: [{ name: "monolog/monolog", version: "2.0.0" }], "packages-dev": [] }), false],
    // yarn v1 is never parsed as empty (fail closed).
    ["yarn.lock", "# THIS IS AN AUTOGENERATED FILE.\n# yarn lockfile v1\n\n", false],
    ["yarn.lock", "__metadata:\n  version: 8\n  cacheKey: 10c0\n\n\"app@workspace:.\":\n  version: 0.0.0-use.local\n  resolution: \"app@workspace:.\"\n", true],
    ["yarn.lock", "# yarn lockfile v1\n\nlodash@^4.17.4:\n  version \"4.17.4\"\n", false],
    ["pnpm-lock.yaml", "lockfileVersion: '9.0'\n\nimporters:\n\n  .: {}\n", true],
    ["pnpm-lock.yaml", "lockfileVersion: '9.0'\n\npackages: {}\n", true],
    ["pnpm-lock.yaml", "lockfileVersion: '9.0'\n\npackages:\n\nsnapshots: {}\n", true],
    ["pnpm-lock.yaml", "lockfileVersion: '9.0'\n\npackages:\n\n  lodash@4.17.4:\n    resolution: {integrity: sha512-x}\n", false],
    ["requirements.txt", "", false],
    // Security review (fail closed): strict YAML parses only.
    ["pnpm-lock.yaml", "lockfileVersion: '9.0'\n\npackages: {}\npackages:\n  lodash@4.17.4:\n    resolution: {integrity: sha512-x}\n", false],
    ["pnpm-lock.yaml", "lockfileVersion: '9.0'\nimporters:\n  .:\n    dependencies:\n      lodash:\n        specifier: ^4.17.4\n        version: 4.17.4\n", false],
    ["pnpm-lock.yaml", "  lockfileVersion: '9.0'\n  packages:\n    lodash@4.17.4: {}\n", false],
    ["pnpm-lock.yaml", "packages:\n\tbad: [\n", false],
    ["yarn.lock", "__metadata:\n  version: 8\n\n\"app@workspace:., lodash@npm:^4.17.4\":\n  version: 4.17.4\n", false],
    ["yarn.lock", "__metadata:\n  version: 8\n\n\"@acme/app@workspace:packages/app, @acme/app@workspace:.\":\n  version: 0.0.0-use.local\n", true],
    ["yarn.lock", "__metadata:\n  version: 8\n__metadata:\n  version: 9\n", false],
    ["yarn.lock", "  version: 8\n  lodash@^4.17.4:\n    version: 4.17.4\n", false],
    ["yarn.lock", "__metadata:\n  version: 8\n\n\"lodash@npm:^4.17.4\":\n  version: 4.17.4\n", false],
  ])("%s %#", (name, text, expected) => {
    expect(isEmptyLockfile(name, text)).toBe(expected);
  });
});
